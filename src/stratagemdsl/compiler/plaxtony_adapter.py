"""Open-source layer 5: type-check generated Galaxy with plaxtony.

plaxtony (MIT, https://github.com/Talv/plaxtony) is the parser and type
checker behind the SC2 Galaxy language server. `vendor/galaxy_checker/`
holds a 40-line driver (check.js); `tools/fetch_galaxy_checker.sh` installs
plaxtony from npm and the core TriggerLibs headers (natives, NativeLib,
GameData) from https://github.com/Talv/sc2-data-trigger.

Unlike galaxycc, plaxtony does not convert Galaxy into GUI trigger XML. The
game executes MapScript.galaxy itself, so packaging writes an empty
TriggerData document (the map then shows no GUI triggers in the editor;
re-saving it there would regenerate MapScript.galaxy from that empty set).
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from stratagemdsl import paths

EMPTY_TRIGGERS = ('<?xml version="1.0" encoding="utf-8"?>\n'
                  '<!-- MapScript.galaxy is generated by StratagemDSL v0.6; the triggers live there. -->\n'
                  '<TriggerData/>\n')
EMPTY_OBJECTS = '<?xml version="1.0" encoding="utf-8"?>\n<PlacedObjects Version="27"/>\n'


class CheckerUnavailable(RuntimeError):
    pass


@dataclass
class GalaxyDiagnostic:
    line: int
    col: int
    severity: str
    message: str

    def __str__(self) -> str:
        return f"{self.line}:{self.col}: {self.severity}: {self.message}"


@dataclass
class PlaxtonyResult:
    ok: bool
    diagnostics: list[GalaxyDiagnostic] = field(default_factory=list)

    @property
    def errors(self) -> list[GalaxyDiagnostic]:
        return [d for d in self.diagnostics if d.severity == "error"]


def checker_dir() -> Path:
    return paths.galaxy_checker_dir()


def available() -> Optional[str]:
    """None when usable, otherwise the reason it is not."""
    root = checker_dir()
    if shutil.which("node") is None:
        return "node is not on PATH"
    if not (root / "node_modules" / "plaxtony").is_dir():
        return f"plaxtony is not installed in {root}; run tools/fetch_galaxy_checker.sh"
    if not (root / "sc2data" / "TriggerLibs" / "natives.galaxy").is_file():
        return f"TriggerLibs headers missing in {root / 'sc2data'}; run tools/fetch_galaxy_checker.sh"
    return None


def check_sources(sources: dict[str, str], *, timeout: float = 600) -> dict[str, PlaxtonyResult]:
    """Check several Galaxy programs in one node process (name -> result)."""
    problem = available()
    if problem:
        raise CheckerUnavailable(problem)
    root = checker_dir()
    with tempfile.TemporaryDirectory(prefix="strat-plaxtony-") as tmp:
        files = {}
        for i, (name, text) in enumerate(sources.items()):
            p = Path(tmp) / f"{i:05d}.galaxy"
            p.write_text(text, encoding="utf-8")
            files[str(p)] = name
        r = subprocess.run(["node", str(root / "check.js"), *files], capture_output=True, text=True,
                           encoding="utf-8", errors="replace",
                           timeout=timeout, cwd=str(root))
        if r.returncode != 0:
            raise RuntimeError(f"plaxtony checker failed ({r.returncode}): {r.stderr.strip()[:500]}")
        rows = json.loads(r.stdout)
    out: dict[str, PlaxtonyResult] = {}
    for row in rows:
        diags = [GalaxyDiagnostic(d["line"], d["col"], d["severity"], d["message"]) for d in row["diagnostics"]]
        out[files[row["file"]]] = PlaxtonyResult(not any(d.severity == "error" for d in diags), diags)
    return out


def check_source(source: str) -> PlaxtonyResult:
    return check_sources({"MapScript.galaxy": source})["MapScript.galaxy"]
